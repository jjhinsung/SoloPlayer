"""Scan the ./music folder and write songs.js for the music player.

Usage:  python generate_songs.py
Run it again any time you add or remove songs.
"""
import json
from pathlib import Path

ROOT = Path(__file__).parent
MUSIC_DIR = ROOT / "music"
AUDIO_EXTS = {".mp3", ".m4a", ".ogg", ".wav", ".flac", ".aac"}

if not MUSIC_DIR.is_dir():
    raise SystemExit(f"No 'music' folder found at {MUSIC_DIR}")

files = sorted(
    (p for p in MUSIC_DIR.rglob("*") if p.suffix.lower() in AUDIO_EXTS),
    key=lambda p: str(p).lower(),
)
paths = [p.relative_to(ROOT).as_posix() for p in files]

out = (
    "// Auto-generated by generate_songs.py\n"
    "window.SONGS = " + json.dumps(paths, indent=2, ensure_ascii=False) + ";\n"
)
(ROOT / "songs.js").write_text(out, encoding="utf-8")
print(f"Wrote {len(paths)} song(s) to songs.js")
